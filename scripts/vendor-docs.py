#!/usr/bin/env python3
"""Vendor product docs from sibling repos into the site tree (ADR-0129 next).

Each public product repo may ship a published-site subtree at
`<repo>/docs/site/` plus a `docs/site.yaml` declaring its site path:

    site_path: graphopt        # -> vendored/graphopt/, served at /graphopt/

The vendored tree lands in `vendored/<site_path>/` (gitignored); VitePress
`rewrites` map `vendored/**` to site-root paths. Sibling dirs are resolved
by their git remote basename, so a checkout named differently from the
repo (e.g. `research-mlopt` -> `graphopt`) still matches.

Private repos, repos without `docs/site/`, and repos not in
`PUBLIC_REPOS` produce nothing — same rule as the Pages clone set.

Run from the docs repo: `python3 scripts/vendor-docs.py`.
"""

from __future__ import annotations

import re
import shutil
import subprocess
import sys
from pathlib import Path

import yaml

DOCS_ROOT = Path(__file__).resolve().parent.parent
ORG = DOCS_ROOT.parent
VENDORED = DOCS_ROOT / "vendored"

PUBLIC_REPOS = {
    "discovery", "docs", "egraph", "engine", "engine-exec",
    "engine-exec-tree-walk", "engine-lex", "engine-lex-pattern",
    "engine-parse", "engine-parse-pratt", "engine-transform", "host",
    "host-tensor", "kernel", "kit-prelude-lang", "research-dts",
    "graphopt", "eqsat", "gamekit", "slidev-theme",
}

# Repo -> site subtree it feeds (fallback: repo name via site.yaml site_path).
# `host` docs vendored under /handl/ is the product mapping; everything
# else defaults to its repo name.
SITE_PATH = {"host": "handl"}

# Project-branch items vendored per product (dirs wholesale, top-level
# docs individually). Retired shells, yaml manifests, assets stay out.
PROJECT_FILES = [
    "TODO.md", "BACKLOG.md", "GOALS.md", "principles.md",
    "research_lab_notebook.md",
    "adrs", "design", "notes", "tasks", "plans", "retros", "reports",
]

# Vendored project paths left out of the published tree — they name a
# private sibling repo, and private siblings produce no pages, links, or
# mentions on this site. Keys are repo names (post-remote resolution);
# values are paths relative to the repo's `project/` dir.
PROJECT_EXCLUDE = {
    "graphopt": {
        "notes/repo-split-plan.md",
        "plans/0032-repo-split.md",
    },
}

NUM = re.compile(r"^(\d+)")
TITLE = re.compile(r"^#\s+(?:ADR-\d+[a-z]?:\s*)?(.*)")

ADRS_SIDEBAR = DOCS_ROOT / ".vitepress" / "sidebar-adrs.mjs"
_adrs: dict[str, list[str]] = {}


def title_of(path: Path) -> str:
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        m = TITLE.match(line)
        if m:
            return m.group(1).strip()
    return path.stem


def collect_adrs(repo: str, product: str, adrs_dir: Path) -> None:
    if not adrs_dir.is_dir():
        return
    items = []
    for f in sorted(adrs_dir.iterdir()):
        if f.suffix != ".md" or not NUM.match(f.name):
            continue
        items.append(
            f'      {{ text: "ADR-{NUM.match(f.name).group(1)} {title_of(f)}",'
            f' link: "/{product}/project/adrs/{f.stem}" }},'
        )
    if items:
        _adrs.setdefault(product, []).extend(items)


def write_adrs_sidebar() -> None:
    """Emit `.vitepress/sidebar-adrs.mjs` — ADR item lists per product."""
    out = ["// GENERATED by scripts/vendor-docs.py — do not edit."]
    for product, items in sorted(_adrs.items()):
        out.append(f'export const {product}Adrs = [')
        out.extend(items)
        out.append("]")
    ADRS_SIDEBAR.write_text("\n".join(out) + "\n", encoding="utf-8")


FENCE = re.compile(r"```.*?```", re.DOTALL)
INLINE = re.compile(r"`[^`\n]*`")
TAG = re.compile(r"<(/?)([a-zA-Z][a-zA-Z0-9-]*)")
HTML_TAGS = {
    "a", "abbr", "address", "article", "aside", "b", "blockquote", "br",
    "caption", "cite", "code", "col", "colgroup", "details", "dd", "del",
    "dfn", "div", "dl", "dt", "em", "figcaption", "figure", "footer",
    "h1", "h2", "h3", "h4", "h5", "h6", "header", "hr", "i", "img",
    "ins", "kbd", "li", "main", "mark", "nav", "ol", "p", "pre", "s",
    "samp", "section", "small", "span", "strong", "sub", "summary", "sup",
    "table", "tbody", "td", "tfoot", "th", "thead", "tr", "u", "ul", "var",
}


def _escape_tags(seg: str) -> str:
    return TAG.sub(
        lambda m: m.group(0) if m.group(2).lower() in HTML_TAGS else f"&lt;{m.group(1)}{m.group(2)}",
        seg,
    )


def sanitize_md(path: Path) -> None:
    """Escape non-HTML `<tag` outside code spans so Vue doesn't treat
    generics/placeholders as unclosed components."""
    text = path.read_text(encoding="utf-8", errors="replace")
    parts = FENCE.split(text)
    fences = FENCE.findall(text)
    out = []
    for i, seg in enumerate(parts):
        bits = INLINE.split(seg)
        inlines = INLINE.findall(seg)
        seg = "".join(
            b if j % 2 else _escape_tags(b)
            for j, b in enumerate(sum(zip(bits, inlines + [""]), ()))
        )
        out.append(seg)
        if i < len(fences):
            out.append(fences[i])
    path.write_text("".join(out), encoding="utf-8")


def remote_name(repo_dir: Path) -> str | None:
    try:
        url = subprocess.run(
            ["git", "-C", str(repo_dir), "remote", "get-url", "origin"],
            capture_output=True, text=True, check=True,
        ).stdout.strip()
    except subprocess.CalledProcessError:
        return None
    name = url.rsplit("/", 1)[-1]
    return name[:-4] if name.endswith(".git") else name


def main() -> int:
    if VENDORED.exists():
        shutil.rmtree(VENDORED)
    VENDORED.mkdir()

    vendored: list[str] = []
    for d in sorted(ORG.iterdir()):
        if not d.is_dir() or d == DOCS_ROOT:
            continue
        repo = remote_name(d)
        if repo not in PUBLIC_REPOS:
            continue
        meta = {}
        yml = d / "docs" / "site.yaml"
        if yml.exists():
            meta = yaml.safe_load(yml.read_text()) or {}
        dest_name = meta.get("site_path") or SITE_PATH.get(repo) or repo
        site_dir = d / "docs" / "site"
        if site_dir.is_dir():
            shutil.copytree(site_dir, VENDORED / dest_name)
            vendored.append(f"{repo} -> /{dest_name}/")
        proj_dir = d / "project"
        if proj_dir.is_dir():
            dest = VENDORED / dest_name / "project"
            dest.mkdir(parents=True, exist_ok=True)
            for item in PROJECT_FILES:
                src = proj_dir / item
                if src.is_dir():
                    shutil.copytree(src, dest / item)
                elif src.is_file():
                    shutil.copy2(src, dest / item)
            for rel in PROJECT_EXCLUDE.get(repo, ()):
                (dest / rel).unlink(missing_ok=True)
            for f in dest.rglob("*.md"):
                sanitize_md(f)
            if not (dest / "index.md").exists():
                (dest / "index.md").write_text(
                    f"# {dest_name} project docs\n\n"
                    f"Vendored from `{repo}`'s `project` branch.\n",
                    encoding="utf-8")
            vendored.append(f"{repo}/project -> /{dest_name}/project/")
            collect_adrs(repo, dest_name, proj_dir / "adrs")

    if vendored:
        print("vendored: " + ", ".join(vendored))
    else:
        print("no product docs vendored (no public sibling ships docs/site/)")
    write_adrs_sidebar()
    return 0


if __name__ == "__main__":
    sys.exit(main())
