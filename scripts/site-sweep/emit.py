#!/usr/bin/env python3
"""Emit Diátaxis site docs for the engine family (sweep helper).

Per repo: README block, docs/site.yaml, docs/site/{index,reference/index,
how-to/index,explanation/index}.md. Content comes from specs_*.py.
"""
import pathlib
import sys

ROOT = pathlib.Path("/home/luis/GitHub/handl-lang")

DOC_BLOCK = """## Documentation

Published site (Diátaxis): <https://handl-lang.github.io/docs/{repo}/>

- [Reference](https://handl-lang.github.io/docs/{repo}/reference/) — public API surface
- [How-to](https://handl-lang.github.io/docs/{repo}/how-to/) — task recipes
- [Explanation](https://handl-lang.github.io/docs/{repo}/explanation/) — design and rationale

Decision records live on the `project` branch under `project/adrs/`.
"""

TPL_INDEX = """# {repo}

{tagline}

## What it is

{what}
{modules}
## Start here

- **Reference** — [public API](/{repo}/reference/)
- **How-to** — [task recipes](/{repo}/how-to/)
- **Explanation** — [design and rationale](/{repo}/explanation/)

No tutorials: this repo is a building block used from Rust. End-to-end
walkthroughs live with the product that composes it — see the
[Handl platform](/handl/).
"""

TPL_REF = """# Reference

## Public API

| item | what it is |
|---|---|
{api}

## Crate

| crate | role |
|---|---|
| `{crate}` | {crate_role} |

## Build and test

```bash
cargo build     # sibling [patch] tables resolve deps from ../<repo>
cargo test      # {tests}
```

Dependencies are git deps on `branch = "main"`; locally the `[patch]` tables
point at sibling checkouts (regenerated by `host/scripts/dev-link.sh`).
"""

TPL_HOWTO = """# How-to guides

Task recipes. Each assumes sibling checkouts of this repo and of the platform
repos it patches.
{sections}"""

TPL_EXPL = """# Explanation

## Why this crate exists

{why}

## Where it sits

This crate belongs to the `engine-*` family. Plugins, kits and hosts reach it
through the kit's operation slot, so the engine can be swapped without touching a
language definition.

See the [reference](/{repo}/reference/) for the API and the
[how-to guides](/{repo}/how-to/) for tasks.
"""

CRATE = {
    "engine": ("hnl-engine", "foundation types"),
    "engine-exec": ("hnl-engine-exec", "abstraction — contract only"),
    "engine-lex": ("hnl-engine-lex", "abstraction — contract only"),
    "engine-parse": ("hnl-engine-parse", "abstraction — contract only"),
    "engine-transform": ("hnl-engine-transform", "abstraction — contract only"),
    "engine-typecheck": ("hnl-engine-typecheck", "abstraction + bootstrap checker"),
    "engine-lex-pattern": ("hnl-engine-lex-pattern", "engine implementation"),
    "engine-parse-pratt": ("hnl-engine-parse-pratt", "engine implementation"),
    "engine-exec-tree-walk": ("hnl-engine-exec-tree-walk", "engine implementation"),
    "engine-exec-bytecode": ("hnl-engine-exec-bytecode", "engine implementation"),
    "engine-transform-rewrite": ("hnl-engine-transform-rewrite", "engine implementation"),
    "kit-prelude-lang": ("handl-kit-prelude-lang", "language definition as data"),
    "egraph": ("handl-egraph", "e-graph substrate"),
    "discovery": ("handl-discovery", "discovery machinery"),
    "host-tensor": ("handl-plugin-host-tensor", "host functions (`tensor.*`)"),
    "lib-char": ("char", "contract (axioms) — pure handl"),
    "lib-char-native": ("handl-plugin-lib-char-native", "Rust backend for `char`"),
    "lib-desugar": ("desugar", "transform-pass source — pure handl"),
    "lib-loader": ("loader", "module loader — pure handl"),
    "lib-str-handl": ("str-handl", "string library — pure handl"),
    "kernel": ("handl-lang/kernel", "substrate workspace"),
    "slidev-theme": ("slidev-theme-handl", "Slidev theme"),
}


def modules_md(spec):
    if not spec["modules"]:
        return ""
    out = ["\n## Modules\n"]
    for name, what in spec["modules"]:
        out.append(f"- {name} — {what}\n")
    return "".join(out) + "\n"


def howto_md(spec):
    out = []
    for title, prose, code in spec["howto"]:
        out.append(f"\n## {title}\n\n{prose}\n")
        if code:
            out.append(f"\n{code}\n" if code.startswith("```") else f"\n```\n{code}\n```\n")
    return "".join(out)


def emit(repo, spec):
    d = ROOT / repo
    site = d / "docs" / "site"
    for sub in ("reference", "how-to", "explanation"):
        (site / sub).mkdir(parents=True, exist_ok=True)
    (d / "docs" / "site.yaml").write_text(f"site_path: {repo}\n")

    api = "\n".join(f"| {a} | {b} |" for a, b in spec["api"])
    crate, role = CRATE[repo]
    files = {
        site / "index.md": TPL_INDEX.format(
            repo=repo, tagline=spec["tagline"], what=spec["what"],
            modules=modules_md(spec)),
        site / "reference" / "index.md": TPL_REF.format(
            api=api, crate=crate, crate_role=role,
            tests=spec["tests"] or "no test suite here — covered by consumers"),
        site / "how-to" / "index.md": TPL_HOWTO.format(sections=howto_md(spec)),
        site / "explanation" / "index.md": TPL_EXPL.format(why=spec["why"], repo=repo),
    }
    for path, text in files.items():
        path.write_text(text if text.endswith("\n") else text + "\n")

    readme = d / "README.md"
    block = DOC_BLOCK.format(repo=repo)
    if readme.exists():
        text = readme.read_text()
        marker = "## Documentation"
        if marker in text:
            text = text.split(marker)[0].rstrip() + "\n\n" + block
        else:
            text = text.rstrip() + "\n\n" + block
    else:
        text = f"# {repo}\n\n`{crate}` — {spec['tagline']}\n\n{block}"
    readme.write_text(text)
    return len(files) + 2


def main():
    from specs import SPECS
    try:
        from specs2 import SPECS2
    except ImportError:
        SPECS2 = {}
    SPECS = {**SPECS, **SPECS2}

    repos = sys.argv[1:] or list(SPECS)
    total = 0
    for repo in repos:
        n = emit(repo, SPECS[repo])
        total += n
        print(f"{repo}: {n} files")
    print(f"-- {total} files across {len(repos)} repos")


if __name__ == "__main__":
    main()
